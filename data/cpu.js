(function () {
  const num = (s) => (s === "" || s == null ? null : Number(s));

  function makerOf(name) {
    if (/^Apple /.test(name)) return "Apple";
    if (/^(Ryzen|AMD)\b/.test(name)) return "AMD";
    return "Intel";
  }

  // 型番から世代・シリーズ名を決める。絞り込みのプルダウンにそのまま出る
  function seriesOf(name) {
    let m;
    if (/^Core Ultra .* Plus$/.test(name)) return "Core Ultra 200S Plus";
    if (/^Core Ultra \d \d{3}/.test(name)) return "Core Ultra 200S";
    if ((m = name.match(/^Core i\d-(\d{2})\d{3}/))) return `第${m[1]}世代 Core`;
    if ((m = name.match(/^Core i\d-(\d)\d{3}/))) return `第${m[1]}世代 Core`;
    if ((m = name.match(/^Ryzen \d (?:PRO )?(\d)\d{3}/))) return `Ryzen ${m[1]}000`;
    if ((m = name.match(/^Apple (M\d)/))) return `Apple ${m[1]}`;
    return "その他";
  }

  const slug = (s) => s.toLowerCase().replace(/コア/g, "c").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

  window.SPEC.data.cpu = CPU_CSV.trim()
    .split("\n")
    .map((line) => {
      const [name, score, cores, threads, tdp, base, boost, cache, price] = line.split(",").map((s) => s.trim());
      const p = num(price);
      return {
        id: slug(name),
        name,
        maker: makerOf(name),
        series: seriesOf(name),
        score: num(score),
        cores: num(cores),
        threads: num(threads),
        tdp: num(tdp),
        baseClock: num(base),
        boostClock: num(boost),
        cache: num(cache),
        price: p,
        // コスパ = 1,000 円あたりの性能スコア（GPU と同じ基準）
        costPerf: p ? Math.round((num(score) / p) * 10000) / 10 : null,
        // 電力効率 = TDP 1W あたりの性能スコア
        efficiency: num(tdp) ? Math.round((num(score) / num(tdp)) * 10) / 10 : null,
      };
    });
})();
